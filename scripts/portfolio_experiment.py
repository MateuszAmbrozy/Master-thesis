"""Run a small, paired multi-seed experiment and export a reviewable report.

This deliberately small experiment demonstrates the workflow, not convergence
or reproduction of the historical study. The PIBT baseline is summarized once,
not counted as independent repetitions across the model training seeds.
"""
import argparse
import csv
import json
import shutil
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]/"src"))
from primal_mapf.runtime import ROOT, project_path, read_config, scenario
from primal_mapf.training import train
from primal_mapf.evaluation.evaluate import evaluate
from primal_mapf.solvers.api import find_path
from primal_mapf.visualization import write_svg


def run(spec: dict, output: Path, report: Path) -> None:
    if output.exists() and any(output.iterdir()):
        raise FileExistsError("Experiment output must be empty")
    if report.exists():
        raise FileExistsError("Report directory must not exist")
    seeds = spec.get("training_seeds")
    if not isinstance(seeds, list) or len(seeds) < 2 or len(set(seeds)) != len(seeds) or any(type(s) is not int or s < 0 for s in seeds):
        raise ValueError("Provide at least two distinct non-negative training seeds")
    output.mkdir(parents=True, exist_ok=True)
    (output/"experiment.json").write_text(json.dumps(spec, indent=2)+"\n")
    results = []
    for seed in seeds:
        models = {}
        for variant in ("classic", "improved"):
            config = read_config(ROOT/f"configs/smoke_{variant}.json")
            config.update(seed=seed, episodes=spec["train_episodes"], agents=spec["agents"], size=spec["size"],
                          density=spec["density"], max_steps=spec["max_steps"], update_steps=8,
                          learning_rate=spec["learning_rate"], demonstration_prob=spec["demonstration_prob"],
                          torch_threads=spec.get("torch_threads", 1), save_every=spec["train_episodes"],
                          execution="joint", environment_profile="common", output=str(output/f"seed_{seed}"/variant))
            models[variant] = str(train(config))
        evaluation = dict(seed=spec["evaluation_seed"], episodes=spec["evaluation_episodes"],
                          agents=spec["agents"], size=spec["size"], density=spec["density"],
                          max_steps=spec["max_steps"], torch_threads=spec.get("torch_threads", 1),
                          greedy=spec["greedy"], models=models, solvers=["pibt"],
                          execution="joint", environment_profile="common", output=str(output/f"seed_{seed}"/"evaluation"))
        results.append((seed, evaluate(evaluation)))
    report.mkdir(parents=True)
    (report/"experiment.json").write_text(json.dumps(spec, indent=2)+"\n")
    for seed in seeds:
        target = report/f"seed_{seed}"
        target.mkdir()
        run_dir = output/f"seed_{seed}"
        for name in ("raw.csv", "scenarios.json", "summary.json", "summary_by_setting.csv", "metadata.json", "config.json"):
            shutil.copy2(run_dir/"evaluation"/name, target/name)
        # Replace machine-specific checkpoint paths with paths relative to the experiment output.
        config = json.loads((target/"config.json").read_text())
        config["models"] = {variant:f"seed_{seed}/{variant}/checkpoint.pt" for variant in ("classic","improved")}
        config["output"] = f"seed_{seed}/evaluation"
        (target/"config.json").write_text(json.dumps(config, indent=2)+"\n")
        for variant in ("classic", "improved"):
            shutil.copy2(run_dir/variant/"training.csv", target/f"training_{variant}.csv")
            shutil.copy2(run_dir/variant/"metadata.json", target/f"metadata_{variant}.json")
            config = json.loads((run_dir/variant/"config.json").read_text())
            config["output"] = f"seed_{seed}/{variant}"
            (target/f"config_{variant}.json").write_text(json.dumps(config, indent=2)+"\n")
    lines = ["# Small multi-seed workflow experiment", "",
             "This report was generated by `scripts/portfolio_experiment.py`. It demonstrates",
             "training and paired evaluation with common environment settings and simultaneous",
             "MAPF transitions. It is not a convergence study or a reproduction of historical results.", "",
             f"Models were trained from scratch for {spec['train_episodes']} episodes per seed",
             f"using training seeds {seeds}. Each model was evaluated on the same",
             f"{spec['evaluation_episodes']} scenario seeds starting at {spec['evaluation_seed']}.",
             f"Maps: {spec['size'][0]} × {spec['size'][1]}, {spec['agents']} agents, requested obstacle density {spec['density']}.",
             f"Step limit: {spec['max_steps']}. Demonstration probability: {spec['demonstration_prob']}; expert: PIBT.", "",
             "## Measurements", "",
             "| Algorithm | Training runs | Success rate, mean ± sample SD across training seeds | Mean successful makespan | Mean elapsed seconds |",
             "| --- | --- | --- | --- | --- |"]
    aggregated = {}
    for name in ("classic", "improved", "pibt"):
        selected = [summary[name] for _,summary in results] if name != "pibt" else [results[0][1][name]]
        rates = [item['success_rate'] for item in selected]
        successful = [item['mean_makespan_successful'] for item in selected if item['mean_makespan_successful'] is not None]
        std = float(np.std(rates, ddof=1)) if len(rates)>1 else None
        mean = float(np.mean(rates))
        makespan = float(np.mean(successful)) if successful else None
        seconds = float(np.mean([item['mean_seconds'] for item in selected]))
        aggregated[name] = dict(training_runs=len(selected) if name != 'pibt' else 0, mean_success_rate=mean,
                                std_success_rate=std, mean_of_successful_makespan_means=makespan, mean_seconds=seconds)
        rate = f"{100*mean:.1f}% ± {100*std:.1f} pp" if std is not None else f"{100*mean:.1f}% (one baseline run)"
        lines.append(f"| {name} | {len(selected) if name != 'pibt' else '—'} | {rate} | {makespan if makespan is not None else '—'} | {seconds:.4f} |")
    lines += ["", "Makespan is reported only for successful attempts. For models, the table averages",
              "the per-training-run means; runs without successes are omitted from that metric.",
              "PIBT is evaluated on the same scenarios in each run, but its baseline is summarized",
              "only once. Timing is hardware-dependent and includes environment setup and trajectory",
              "validation for policies. No claim of equal computational budgets is made.", "",
              "Per-run success intervals in `summary.json` use Wilson 95% intervals over scenarios.",
              "The same scenarios are reused across training seeds, so these are paired measurements;",
              "they must not be pooled as independent trials. Three short training runs are insufficient",
              "to establish a general architectural advantage.", "",
              "## Interpretation", "",
              "The experiment verifies that both networks can train, save checkpoints, and be evaluated",
              "under shared rules. The small training budget does not establish policy quality.",
              "Low success rates are retained as measured; successful coordination in the illustration",
              "below comes from PIBT, not from either learned policy.", "",
              "![PIBT trajectory on the first evaluation scenario](trajectory.svg)", "",
              "## Reproduction", "", "Run from the repository root:", "", "```bash",
              "python scripts/portfolio_experiment.py --config configs/portfolio.json --output results/portfolio_repeat --report results/portfolio_report_repeat",
              "```", "", "The report contains configurations, exact scenarios, raw measurements, training logs,",
              "and runtime metadata with dependency versions, source hashes, and checkpoint hashes.",
              "Report configuration paths are relative to the experiment output directory; to replay",
              "them directly, make the model and output paths absolute first. Checkpoints remain in",
              "the local experiment output and are not copied into this report.", ""]
    (report/"README.md").write_text('\n'.join(lines))
    (report/"aggregate.json").write_text(json.dumps(aggregated, indent=2)+"\n")
    obstacles, starts, goals = scenario(spec, spec['evaluation_seed'])
    trace = find_path('pibt', obstacles, starts, goals, max_steps=spec['max_steps'], seed=spec['evaluation_seed'])
    if trace is None:
        raise RuntimeError("PIBT did not solve the illustration scenario")
    write_svg(report/'trajectory.svg', obstacles, starts, goals, trace, title='PIBT reference trajectory', animate=True)
    print(f"Portfolio report: {report}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', default='configs/portfolio.json')
    parser.add_argument('--output', default='results/portfolio')
    parser.add_argument('--report', default='results/portfolio_report')
    args = parser.parse_args()
    run(read_config(args.config), project_path(args.output).resolve(), project_path(args.report).resolve())


if __name__ == '__main__':
    main()
